// Weapons the route planner counts for Enhancement (two-handed axes and
// maces): quest rewards by quest id and dungeon boss drops by dungeon, from
// the site's data/weapons.json. The planner (polestar-sim-shaman.patch)
// reads planner/weapons-enhancement.json: a better weapon makes every later
// kill faster, so a detour to a dungeon quest that gives one can pay off.
//
//   node planner/build-weapons.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const { weapons } = JSON.parse(fs.readFileSync(path.join(root, 'data', 'weapons.json'), 'utf8'));
const KINDS = new Set(['2H Axe', '2H Mace']);

const quests = {};
const drops = {};
for (const w of weapons) {
  if (!KINDS.has(w.kind)) continue;
  for (const s of w.sources) {
    if (s.type === 'quest' && s.questId && s.faction !== 'alliance') {
      // A quest offering several: the best one.
      if (!quests[s.questId] || quests[s.questId].dps < w.dps) quests[s.questId] = { dps: w.dps, req: w.req, name: w.name };
    } else if (s.type === 'boss' && s.zone && s.faction !== 'alliance') {
      (drops[s.zone] = drops[s.zone] || []).push({ dps: w.dps, req: w.req, name: w.name, boss: s.npc });
    }
  }
}

const out = {
  note: 'Generated by planner/build-weapons.js from data/weapons.json; Enhancement (2H Axe, 2H Mace), Horde.',
  build: JSON.parse(fs.readFileSync(path.join(root, 'data', 'weapons.json'), 'utf8')).build,
  quests,
  drops
};
fs.writeFileSync(path.join(__dirname, 'weapons-enhancement.json'), JSON.stringify(out, null, 1) + '\n');
console.log('weapons-enhancement.json: ' + Object.keys(quests).length + ' quests, ' + Object.keys(drops).length + ' dungeons');
